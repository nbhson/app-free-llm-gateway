// Load .env from repo root regardless of cwd (npm run dev -w apps/gateway sets cwd to apps/gateway)
let loadedEnvPath: string | null = null;
try {
  const __filename = fileURLToPath(import.meta.url);
  const __dirname = path.dirname(__filename);
  const candidates = [
    path.resolve(".env"),
    path.resolve(path.join(process.cwd(), ".env")),
    path.resolve(path.join(__dirname, "../../../.env")),
    path.resolve(path.join(__dirname, "../../.env")),
    path.resolve("/app/.env"),
  ];
  for (const p of candidates) {
    if (fs.existsSync(p)) {
      dotenv.config({ path: p });
      loadedEnvPath = p;
      break;
    }
  }
  // Fallback to default dotenv (cwd)
  if (!process.env.MASTER_KEY) dotenv.config();
} catch {
  /* ignore: dotenv fallback */
  dotenv.config();
}

function isPlaceholderMaster(v: string | undefined): boolean {
  if (!v) return true;
  return v.includes("change-me") || v === "fgk-master-dev-key" || v.trim().length < 16;
}
function isPlaceholderEncryption(v: string | undefined): boolean {
  if (!v) return true;
  const hex = v.replace(/[^0-9a-f]/gi, "");
  return hex.length < 64 || v.includes("0123456789abcdef0123456789abcdef");
}
function tryLoadPersistedFallback(): void {
  // If .env missing (Docker without env_file), reuse keys from data/.gateway-keys.json
  if (!isPlaceholderMaster(process.env.MASTER_KEY) && !isPlaceholderEncryption(process.env.ENCRYPTION_KEY)) return;
  const candidates = [
    path.resolve("data/.gateway-keys.json"),
    path.resolve(path.join(process.cwd(), "data/.gateway-keys.json")),
    path.resolve("/app/data/.gateway-keys.json"),
  ];
  try {
    const __filename = fileURLToPath(import.meta.url);
    const __dirname = path.dirname(__filename);
    candidates.unshift(path.resolve(path.join(__dirname, "../../../data/.gateway-keys.json")));
    candidates.unshift(path.resolve(path.join(__dirname, "../../data/.gateway-keys.json")));
  } catch { /* ignore: __dirname unavailable */ }
  for (const p of candidates) {
    try {
      if (fs.existsSync(p)) {
        const j = JSON.parse(fs.readFileSync(p, "utf-8"));
        if (isPlaceholderMaster(process.env.MASTER_KEY) && j.MASTER_KEY) process.env.MASTER_KEY = j.MASTER_KEY;
        if (isPlaceholderEncryption(process.env.ENCRYPTION_KEY) && j.ENCRYPTION_KEY) process.env.ENCRYPTION_KEY = j.ENCRYPTION_KEY;
        if (!isPlaceholderMaster(process.env.MASTER_KEY) || !isPlaceholderEncryption(process.env.ENCRYPTION_KEY)) {
          console.warn(`[config] Restored keys from ${p}`);
          break;
        }
      }
    } catch { /* ignore: key file unreadable */ }
  }
}
function ensureKeysAutoGenerated() {
  let changed = false;
  if (isPlaceholderMaster(process.env.MASTER_KEY)) {
    const gen = `fgk-master-${crypto.randomBytes(16).toString("hex")}`;
    process.env.MASTER_KEY = gen;
    changed = true;
    // Never log full key — even dev logs can leak via Docker/CI. Show prefix only.
    // Full value is persisted to .env / data/.gateway-keys.json for the operator.
    console.warn(`[config] Auto-generated MASTER_KEY=${gen.slice(0, 14)}... (redacted, see .env or data/.gateway-keys.json)`);
  }
  if (isPlaceholderEncryption(process.env.ENCRYPTION_KEY)) {
    const gen = crypto.randomBytes(32).toString("hex");
    process.env.ENCRYPTION_KEY = gen;
    changed = true;
    console.warn(`[config] Auto-generated ENCRYPTION_KEY=${gen.slice(0, 8)}... (no valid .env value found)`);
  }
  if (changed && loadedEnvPath) {
    try {
      let content = fs.readFileSync(loadedEnvPath, "utf-8");
      if (process.env.MASTER_KEY) {
        if (content.includes("MASTER_KEY=")) content = content.replace(/^MASTER_KEY=.*$/m, `MASTER_KEY=${process.env.MASTER_KEY}`);
        else content += `\nMASTER_KEY=${process.env.MASTER_KEY}\n`;
      }
      if (process.env.ENCRYPTION_KEY) {
        if (content.includes("ENCRYPTION_KEY=")) content = content.replace(/^ENCRYPTION_KEY=.*$/m, `ENCRYPTION_KEY=${process.env.ENCRYPTION_KEY}`);
        else content += `\nENCRYPTION_KEY=${process.env.ENCRYPTION_KEY}\n`;
      }
      fs.writeFileSync(loadedEnvPath, content);
      console.warn(`[config] Persisted auto-generated keys to ${loadedEnvPath}`);
    } catch (e) {
      console.warn(`[config] Could not persist auto-generated keys to ${loadedEnvPath}:`, (e as Error).message);
    }
  } else if (changed) {
    // No .env file found (e.g. Docker without env_file) — persist to data dir for next restart
    try {
      const dataDir = loadedEnvPath ? path.dirname(loadedEnvPath) : path.resolve("data");
      const persistPath = path.join(dataDir, ".gateway-keys.json");
      // also try /app/data
      const candidates = [persistPath, "/app/data/.gateway-keys.json", path.resolve(process.cwd(), "data/.gateway-keys.json")];
      const target = candidates[0];
      fs.mkdirSync(path.dirname(target), { recursive: true });
      fs.writeFileSync(target, JSON.stringify({ MASTER_KEY: process.env.MASTER_KEY, ENCRYPTION_KEY: process.env.ENCRYPTION_KEY }, null, 2));
      console.warn(`[config] Persisted auto-generated keys to ${target} (fallback, no .env found)`);
    } catch { /* ignore: fallback persist failed */ }
  }
}
tryLoadPersistedFallback();
ensureKeysAutoGenerated();

