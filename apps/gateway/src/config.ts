function parseTiers(): string[][] {
  try {
    const raw = process.env.FALLBACK_TIERS;
    if (!raw) return [[...DEFAULT_FALLBACK_TIER]];
    const parsed = JSON.parse(raw) as unknown;
    if (!Array.isArray(parsed) || parsed.length === 0) return [[...DEFAULT_FALLBACK_TIER]];
    // Validate: array of arrays of non-empty strings, cap size to prevent DoS
    const tiers: string[][] = [];
    for (const tier of parsed) {
      if (!Array.isArray(tier)) return [[...DEFAULT_FALLBACK_TIER]];
      const clean = tier.filter((p): p is string => typeof p === "string" && p.trim().length > 0).slice(0, 60);
      if (clean.length === 0) return [[...DEFAULT_FALLBACK_TIER]];
      tiers.push(clean);
      if (tiers.length >= 8) break;
    }
    return tiers;
  } catch {
    return [[...DEFAULT_FALLBACK_TIER]];
  }
}

function parseKeys(env: string | undefined): string[] {
  if (!env) return [];
  return env.split(",").map((s) => s.trim()).filter(Boolean);
}

function parseBoolEnv(v: string | undefined): boolean {
  if (!v) return false;
  const s = v.trim().toLowerCase();
  return s === "1" || s === "true" || s === "yes" || s === "on";
}

